<#
.SYNOPSIS
  Runs the PowerShell app's own status code (Get-AppRows from Wintainium.ps1) on the cases in
  status-cases.json and saves its answers as status-golden.json. The C# port's tests compare
  against that file, so both versions are checked against the same inputs.

  Run it again only if the cases change:  pwsh -NoProfile -File tests/golden/Make-StatusGolden.ps1
  Dates in the cases are at 12:00 UTC so the local-date columns don't depend on the time zone.
#>
$ErrorActionPreference = 'Stop'
$goldenDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
$repo = Split-Path -Parent (Split-Path -Parent $goldenDir)
$ast = [System.Management.Automation.Language.Parser]::ParseFile((Join-Path $repo 'Wintainium.ps1'), [ref]$null, [ref]$null)
$want = 'ConvertTo-Utc', 'Test-SelfEntry', 'Test-OlderVersion', 'Get-AppRows'
foreach ($f in $ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -in $want }, $true)) {
    . ([scriptblock]::Create($f.Extent.Text))
}
$script:AppVersion = [regex]::Match((Get-Content -Raw (Join-Path $repo 'Wintainium.ps1')), "AppVersion = '([\d.]+)'").Groups[1].Value
$script:Here = Join-Path ([IO.Path]::GetTempPath()) 'wintainium-golden-self'
$GraceDays = 3
$script:settings = [pscustomobject]@{}
$viaLabel = @{ emudeck = 'EmuDeck'; inapp = 'in-app'; installer = 'installer'; zip = 'zip install'; download = 'download'; page = 'release page' }

$cases = @(Get-Content -Raw (Join-Path $goldenDir 'status-cases.json') | ConvertFrom-Json | ForEach-Object { $_ })
$byExe = @{}
$byName = @{}
$script:apps = foreach ($c in $cases) {
    $c.app.exe = ([string]$c.app.exe).Replace('{HERE}/', $script:Here + [IO.Path]::DirectorySeparatorChar)
    $byExe[[string]$c.app.exe] = $c
    $byName[[string]$c.app.name] = $c
    $c.app
}

# Stand-ins for the file system and the network, fed from the cases.
function Write-Host { }
function Save-Cache { }
function Test-Path { param([string]$LiteralPath) $c = $byExe[$LiteralPath]; return [bool]($c -and $c.exe) }
function Get-Item {
    param([string]$LiteralPath)
    $c = $byExe[$LiteralPath]
    [pscustomobject]@{
        LastWriteTimeUtc = ([DateTimeOffset]::Parse($c.exe.written, [Globalization.CultureInfo]::InvariantCulture)).UtcDateTime
        VersionInfo      = [pscustomobject]@{ ProductVersion = [string]$c.exe.version }
    }
}
function Get-LookupStatus($err, $app) { return [string]$byName[[string]$app.name].fail }
function Get-LatestCached($app, [switch]$Force) {
    $c = $byName[[string]$app.name]
    if ($c.fail) { throw 'lookup failed in the case' }
    if (-not $c.release) { return $null }
    $tag = ([string]$c.release.tag).Replace('{SELF}', $script:AppVersion)
    $date = if ($c.release.date) { ([DateTimeOffset]::Parse($c.release.date, [Globalization.CultureInfo]::InvariantCulture)).UtcDateTime } else { $null }
    $stale = $null
    if ($c.stale) { $stale = [pscustomobject]@{ Reason = $c.stale.reason; Site = $c.stale.site; Fetched = ([DateTimeOffset]::Parse($c.stale.fetched, [Globalization.CultureInfo]::InvariantCulture)).UtcDateTime } }
    return [pscustomobject]@{ Tag = $tag; Date = $date; Page = 'https://example.org/release'; Assets = @(); Notes = ''; Stale = $stale }
}

$rows = Get-AppRows
$out = [ordered]@{
    note    = 'Generated by Make-StatusGolden.ps1 from Wintainium.ps1 v' + $script:AppVersion + '. Do not edit by hand.'
    version = $script:AppVersion
    rows    = @($rows | ForEach-Object {
        [ordered]@{ App = $_.App; Status = $_.Status; Installed = $_.Installed; Latest = $_.Latest; Released = $_.Released; Via = [string]$_.Via; Gold = [bool]$_.Gold }
    })
}
$json = $out | ConvertTo-Json -Depth 5
[IO.File]::WriteAllText((Join-Path $goldenDir 'status-golden.json'), $json + "`n", [Text.UTF8Encoding]::new($false))
"Wrote $($out.rows.Count) rows to status-golden.json"
